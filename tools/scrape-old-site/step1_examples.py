def save(slug, page):
    with open(f"{ROOT}/content/pages/{slug}.json", "w", encoding="utf-8") as f:
        json.dump({"$schema": "../blocks.schema.json", **page}, f, ensure_ascii=False, indent=2)
        f.write("\n")
    html = (TPL.replace("[แก้ไข] คำอธิบายหน้านี้ 1-2 ประโยค สำหรับ SEO", page["description"])
               .replace("[แก้ไข] ชื่อหน้า", page["title"])
               .replace("[แก้ไข-navKey]", page["navKey"])
               .replace("[แก้ไข-slug]", slug))
    assert "แก้ไข" not in html, slug
    with open(f"{ROOT}/{slug}.html", "w", encoding="utf-8", newline="\n") as f:
        f.write(html)


